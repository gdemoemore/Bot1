def _core():
    majors = [dict(id=f"major_{i:02d}", name=n, icon="✨", up=u, rev=r, theme=None, suit="major")
              for i, (n, u, r) in enumerate(MAJOR)]
    minors = {}
    for key, (gen, icon, theme, _elem) in SUITS.items():
        minors[key] = [
            dict(id=f"{key}_{n:02d}", name=f"{rank} {gen}", icon=icon,
                 up=up, rev=rev, theme=theme, suit=key)
            for n, (rank, up, rev) in enumerate(RANKS, start=1)
        ]
    return majors, minors


MAJORS, MINORS = _core()


def _load_extras() -> list[dict]:
    p = Path(__file__).parent / "data" / "extras.json"
    if not p.exists():
        return []
    out = []
    for c in json.loads(p.read_text("utf-8")):
        c.setdefault("icon", "🔮")
        c.setdefault("theme", None)
        c.setdefault("suit", "extra")
        out.append(c)
    return out


EXTRAS = _load_extras()
ALL_ALTERNATES = [dict(theme=None, suit="alt", **a) for a in ALTERNATES] + [c for c in EXTRAS if c.get("replaces")]
ADDITIONS = _BUILTIN_ADD + [c for c in EXTRAS if not c.get("replaces")]


def build_deck(cups_mode: str = "cups", alts: bool = False,
               rng: random.Random | None = None, need78: bool = False,
               extras: bool = False) -> list[dict]:
    """
    cups_mode: 'cups' | 'vessels' (Сосуды вместо Кубков) | 'both' (5 мастей)
    alts: подмешивать альтернативные карты Terra Volatile
    need78: метод требует ровно 78 карт (Мазерс): 'both' → 'cups', дополнения не добавляются
    extras: добавить дополнительные карты (Рыцарь, Возрождение, …)
    """
    rng = rng or random.Random()
    mode = "cups" if (need78 and cups_mode == "both") else cups_mode

    deck = list(MAJORS)
    if mode in ("cups", "both"):
        deck += MINORS["cups"]
    if mode in ("vessels", "both"):
        deck += MINORS["vessels"]
    for s in ("coins", "swords", "wands"):
        deck += MINORS[s]

    if alts:
        pos = {c["id"]: i for i, c in enumerate(deck)}
        for alt in ALL_ALTERNATES:
            i = pos.get(alt["replaces"])
            if i is None:
                continue
            if mode == "both" and not need78:
                deck.append(alt)             # вся колода целиком: альтернативы добавляются
            elif rng.random() < 0.5:
                deck[i] = alt                # 78 карт: альтернатива случайно заменяет классику
    if extras and not need78:
        deck += ADDITIONS
    return deck


def pool_for(deck: list[dict], pool: str | None) -> list[dict]:
    """pool: None — вся колода, 'major' — старшие арканы, иначе ключ масти (cups/coins/…)."""
    if pool is None:
        return deck
    if pool == "court":
        out = []
        for c in deck:
            suit, _, num = c["id"].rpartition("_")
            if suit in MINORS and num.isdigit() and int(num) >= 11:
                out.append(c)
        return out
    if pool == "major":
        return [c for c in deck if c["suit"] in ("major", "alt") and c["id"].startswith(("major", "alt"))]
    if pool in MINORS:
        return MINORS[pool]
    return deck


def draw(pool: list[dict], n: int, reversals: bool, rng: random.Random,
         exclude: set[str] | None = None) -> list[tuple[dict, bool]]:
    exclude = exclude or set()
    avail = [c for c in pool if c["id"] not in exclude]
    cards = rng.sample(avail, n)
    return [(c, reversals and rng.random() < 0.35) for c in cards]
