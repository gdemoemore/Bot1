def summary(drawn: list[tuple[dict, bool]]) -> str:
    n = len(drawn)
    if n < 3:
        return ""
    lines = []
    majors = sum(1 for c, _ in drawn if c["id"].startswith(("major", "alt")))
    revs = sum(1 for _, r in drawn if r)
    if majors >= max(3, n * 0.4):
        lines.append("Старших Арканов здесь много: событие больше тебя, и речь идёт о судьбе, а не о случайности.")
    elif majors == 0:
        lines.append("Старших Арканов нет: всё решается в повседневности, твоими руками.")
    if revs >= n * 0.5:
        lines.append("Много перевёрнутых карт: многое сейчас скрыто, заторможено или пока не созрело.")
    elif revs == 0:
        lines.append("Все карты прямые: энергия течёт свободно, преград почти нет.")
    if n >= 5:
        counts: dict[str, int] = {}
        for c, _ in drawn:
            s = c.get("suit")
            if s in _SUIT_DOM:
                counts[s] = counts.get(s, 0) + 1
        if counts:
            s, cnt = max(counts.items(), key=lambda x: x[1])
            if cnt >= max(3, n * 0.35):
                lines.append(_SUIT_DOM[s])
    if not lines:
        return ""
    return "🌗 <b>Дыхание расклада</b>\n" + " ".join(lines)
