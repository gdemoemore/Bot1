def literary(card: dict, rev: bool) -> str:
    """Развёрнутое описание карты для данной ориентации."""
    k = 1 if rev else 0
    custom = card.get("lit_rev" if rev else "lit_up")
    if custom:
        return custom
    cid = card["id"]
    if cid in MAJOR_LIT:
        return MAJOR_LIT[cid][k]
    if cid in ALT_LIT:
        return ALT_LIT[cid][k]
    suit, _, num = cid.rpartition("_")
    if suit in SUIT_SCENE and num.isdigit() and 1 <= int(num) <= 14:
        return f"{RANK_LIT[int(num) - 1][k]} {SUIT_SCENE[suit][k]}"
    kw = card["rev"] if rev else card["up"]
    return kw[:1].upper() + kw[1:] + "."


